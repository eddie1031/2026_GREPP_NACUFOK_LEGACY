ALTER SESSION SET CONTAINER = DPSTPRD;
ALTER SESSION SET CURRENT_SCHEMA = DPST_APP;

CREATE OR REPLACE PACKAGE PKG_DPST_TAX AS
    PROCEDURE SP_CALC_TAX (
        P_ACNO IN VARCHAR2,
        P_INTR_AMT IN NUMBER,
        P_PDCD IN VARCHAR2,
        P_TAX_AMT OUT NUMBER
    );
END PKG_DPST_TAX;
/

CREATE OR REPLACE PACKAGE BODY PKG_DPST_TAX AS
    PROCEDURE SP_CALC_TAX (
        P_ACNO IN  VARCHAR2,
        P_INTR_AMT IN  NUMBER,
        P_PDCD IN  VARCHAR2,
        P_TAX_AMT OUT NUMBER
    ) IS
    BEGIN
        P_TAX_AMT := TRUNC(P_INTR_AMT * 0.154);
    END SP_CALC_TAX;
END PKG_DPST_TAX;
/
