-- bank-deposit-legacy
-- init 스크립트는 매번 새 sqlplus 프로세스(/ as sysdba, CDB ROOT)로 실행되므로
-- 매 파일 상단에서 PDB/스키마를 명시적으로 지정해야 DPST_APP 소유로 생성된다.
ALTER SESSION SET CONTAINER = DPSTPRD;
ALTER SESSION SET CURRENT_SCHEMA = DPST_APP;

CREATE TABLE TB_CUST (
    CUST_NO VARCHAR2(10) NOT NULL,
    CUST_NM VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_TB_CUST PRIMARY KEY (CUST_NO)
);

-- 상품, 적용일자별 금리 (계좌는 개설일자 기준 금리를 사용)
CREATE TABLE TB_INTR_RATE (
    PDCD VARCHAR2(4) NOT NULL,
    APLY_DT VARCHAR2(8) NOT NULL,
    BSRT NUMBER(5,2) NOT NULL, -- 기본금리(연 %)
    PRFT_RT NUMBER(5,2), -- 우대금리(연 %)
    CONSTRAINT PK_TB_INTR_RATE PRIMARY KEY (PDCD, APLY_DT)
);

-- 계좌상태코드 ACNT_STCD: 1 정상, 9 해지, 5 휴면
CREATE TABLE TB_DPST_ACNT (
    ACNO VARCHAR2(14) NOT NULL,
    CUST_NO VARCHAR2(10) NOT NULL,
    PDCD VARCHAR2(4) NOT NULL,
    PRCP_AMT NUMBER(15) NOT NULL,
    OPN_DT VARCHAR2(8) NOT NULL,
    MTRT_DT VARCHAR2(8) NOT NULL,
    ACNT_STCD VARCHAR2(1) DEFAULT '1' NOT NULL,
    CNCL_DT VARCHAR2(8),
    CONSTRAINT PK_TB_DPST_ACNT PRIMARY KEY (ACNO)
);

CREATE TABLE TB_DPST_CLOSE_HIST (
    ACNO VARCHAR2(14) NOT NULL,
    CNCL_DT VARCHAR2(8) NOT NULL,
    INTR_AMT NUMBER(15) NOT NULL,
    TAX_AMT NUMBER(15) NOT NULL,
    REG_DTM DATE NOT NULL
);
